/// Exit code: success (`check`: no errors).
const int exitOk = 0;

/// Exit code: `check` found errors, or a command could not do its job.
const int exitProblems = 1;

/// Exit code: bad command line or invalid `husk.yaml`.
const int exitUsage = 2;

const _commands = {
  'init': 'Write a starter husk.yaml.',
  'generate': 'Write the SwiftPM, CocoaPods, Gradle and Dart glue.',
  'link': 'Copy the vendor binaries into the git-ignored husk_vendor/ folders.',
  'unlink': 'Remove the copied binaries; builds fall back to the stub.',
  'doctor': 'Explain what was found and how the next build will link.',
  'check': 'CI gate. Exit 0: fine, 1: problems, 2: usage or husk.yaml error.',
};

const _clearCacheHelp =
    'Also delete the Swift Package Manager manifest cache (macOS), so the '
    'next build re-reads Package.swift.';

ArgParser _parser() {
  final parser = ArgParser()
    ..addOption(
      'project',
      abbr: 'C',
      valueHelp: 'dir',
      help: 'Project directory that holds husk.yaml.',
      defaultsTo: '.',
    )
    ..addFlag('help', abbr: 'h', negatable: false, help: 'Show usage.')
    ..addFlag('version', negatable: false, help: 'Print the version.');
  parser.addCommand(
    'init',
    ArgParser()
      ..addOption(
        'sdk',
        valueHelp: 'Name',
        help: 'Swift module name of the SDK (required).',
      )
      ..addOption(
        'sdk-version',
        valueHelp: 'x.y.z',
        help: 'Expected SDK version.',
      )
      ..addOption(
        'aar',
        valueHelp: 'glob',
        help: "AAR file name or glob (default '*.aar').",
      )
      ..addOption(
        'android-package',
        valueHelp: 'pkg',
        help: 'Kotlin package for generated code.',
      )
      ..addFlag(
        'ios',
        defaultsTo: null,
        help: 'Configure iOS (default: if ios/ exists).',
      )
      ..addFlag(
        'android',
        defaultsTo: null,
        help: 'Configure Android (default: if android/ exists).',
      )
      ..addFlag(
        'force',
        negatable: false,
        help: 'Overwrite an existing husk.yaml.',
      ),
  );
  parser.addCommand(
    'generate',
    ArgParser()
      ..addFlag(
        'dry-run',
        negatable: false,
        help: 'Show what would change; write nothing.',
      )
      ..addFlag(
        'force',
        negatable: false,
        help: 'Overwrite files that were not generated by husk_sdk.',
      ),
  );
  parser.addCommand(
    'link',
    ArgParser()
      ..addOption(
        'from',
        valueHelp: 'dir',
        help:
            'Directory with the vendor files (default: the spec env variable).',
      )
      ..addFlag('clear-swiftpm-cache', negatable: false, help: _clearCacheHelp),
  );
  parser.addCommand(
    'unlink',
    ArgParser()
      ..addFlag('clear-swiftpm-cache', negatable: false, help: _clearCacheHelp),
  );
  for (final name in const ['doctor', 'check']) {
    final sub = ArgParser()
      ..addOption(
        'from',
        valueHelp: 'dir',
        help: 'Also look for the vendor files here.',
      )
      ..addFlag(
        'json',
        negatable: false,
        help:
            'Print the report as JSON, including the exit code check would use.',
      );
    if (name == 'check') {
      sub.addMultiOption(
        'require-sdk',
        allowed: platforms,
        valueHelp: 'platform',
        help: 'Fail when the SDK binary for this platform is missing.',
      );
    }
    parser.addCommand(name, sub);
  }
  for (final sub in parser.commands.values) {
    sub.addFlag('help', abbr: 'h', negatable: false, help: 'Show usage.');
  }
  return parser;
}

/// Runs the CLI with [args] and returns the process exit code.
///
/// [out] and [err] default to stdout and stderr; [environment] defaults to
/// the process environment. Both are injectable for tests.
int runCli(
  List<String> args, {
  StringSink? out,
  StringSink? err,
  Map<String, String>? environment,
}) {
  final o = out ?? stdout;
  final e = err ?? stderr;
  final env = environment ?? Platform.environment;
  final parser = _parser();
  final ArgResults results;
  try {
    results = parser.parse(args);
  } on FormatException catch (x) {
    e
      ..writeln(x.message)
      ..writeln()
      ..writeln(_usage(parser));
    return exitUsage;
  }
  if (results.flag('version')) {
    o.writeln('husk_sdk $packageVersion');
    return exitOk;
  }
  final command = results.command;
  if (results.flag('help') || command == null) {
    (command == null && !results.flag('help') ? e : o).writeln(_usage(parser));
    return results.flag('help') ? exitOk : exitUsage;
  }
  final root = p.normalize(p.absolute(results.option('project')!));
  if (!Directory(root).existsSync()) {
    e.writeln('Project directory $root does not exist.');
    return exitUsage;
  }
  try {
    switch (command.name) {
      case 'init':
        return _init(command, root, o, e);
      case 'generate':
        return _generate(HuskSpec.load(root), command, o, e);
      case 'link':
        return _link(HuskSpec.load(root), command, env, o, e);
      case 'unlink':
        return _unlink(HuskSpec.load(root), command, env, o);
      case 'doctor':
        return _report(HuskSpec.load(root), command, env, o, strict: false);
      case 'check':
        return _report(HuskSpec.load(root), command, env, o, strict: true);
    }
  } on SpecException catch (x) {
    e.writeln(x.message);
    return exitUsage;
  } on FileSystemException catch (x) {
    e.writeln(
      '${x.path ?? ''}: ${x.message} ${x.osError?.message ?? ''}'.trim(),
    );
    return exitProblems;
  }
  return exitUsage;
}

String _usage(ArgParser parser) {
  final b = StringBuffer()
    ..writeln(
      'Build Flutter plugins with or without a closed-source native SDK.',
    )
    ..writeln()
    ..writeln('Usage: dart run husk_sdk [-C <dir>] <command> [options]')
    ..writeln()
    ..writeln('Commands:');
  _commands.forEach((name, help) => b.writeln('  ${name.padRight(10)} $help'));
  b
    ..writeln()
    ..writeln('Global options:')
    ..writeln(parser.usage)
    ..writeln()
    ..write('Run `dart run husk_sdk <command> --help` for command options.');
  return b.toString();
}

bool _commandHelp(ArgResults command, StringSink o) {
  if (command.flag('help')) {
    o
      ..writeln('Usage: dart run husk_sdk ${command.name} [options]')
      ..writeln(_parser().commands[command.name]!.usage);
    return true;
  }
  return false;
}

int _init(ArgResults c, String root, StringSink o, StringSink e) {
  if (_commandHelp(c, o)) return exitOk;
  final sdk = c.option('sdk');
  if (sdk == null) {
    e.writeln('init needs --sdk <Name>, the Swift module name of the SDK.');
    return exitUsage;
  }
  final file = File(p.join(root, specFileName));
  if (file.existsSync() && !c.flag('force')) {
    e.writeln('${file.path} exists; pass --force to replace it.');
    return exitProblems;
  }
  final text = initialSpec(
    root,
    sdkName: sdk,
    version: c.option('sdk-version'),
    aar: c.option('aar'),
    androidPackage: c.option('android-package'),
    ios: c.wasParsed('ios') ? c.flag('ios') : null,
    android: c.wasParsed('android') ? c.flag('android') : null,
  );
  file.writeAsStringSync(text);
  o
    ..writeln('Wrote $specFileName.')
    ..writeln('Next: dart run husk_sdk generate');
  return exitOk;
}

int _generate(HuskSpec spec, ArgResults c, StringSink o, StringSink e) {
  if (_commandHelp(c, o)) return exitOk;
  final dryRun = c.flag('dry-run');
  final outcomes = applyPlan(
    spec.root,
    planFiles(spec),
    dryRun: dryRun,
    force: c.flag('force'),
  );
  o.writeln('husk_sdk generate: ${spec.sdkName}${dryRun ? ' (dry run)' : ''}');
  var failed = false;
  for (final x in outcomes) {
    final label = switch (x.status) {
      FileStatus.unchanged => 'unchanged',
      FileStatus.created => dryRun ? 'would create' : 'created',
      FileStatus.updated => dryRun ? 'would update' : 'updated',
      FileStatus.failed => 'FAILED',
    };
    o.writeln('  ${label.padRight(12)} ${x.path}');
    if (x.status == FileStatus.failed) {
      failed = true;
      e.writeln('${x.path}: ${x.message}');
    }
  }
  if (failed) return exitProblems;
  final missing = [
    for (final s in diagnose(spec, env: const {}))
      for (final f in s.findings)
        if (f.level == Level.error && f.message.startsWith('nothing calls'))
          f.message,
  ];
  final type = channelType(spec);
  final steps = [
    if (missing.any((m) => m.contains('$type.register(with:')))
      '  iOS:     call $type.register(with: registrar) in register(with:)',
    if (missing.any((m) => m.contains('$type.attach(')))
      '  Android: call $type.attach(binding.binaryMessenger) in '
          'onAttachedToEngine (and detach in onDetachedFromEngine)',
  ];
  if (steps.isNotEmpty) {
    o
      ..writeln()
      ..writeln('Wire the generated channel into the plugin class:')
      ..writeAll(steps, '\n')
      ..writeln();
  }
  return exitOk;
}

int _link(
  HuskSpec spec,
  ArgResults c,
  Map<String, String> env,
  StringSink o,
  StringSink e,
) {
  if (_commandHelp(c, o)) return exitOk;
  final results = link(spec, env: env, from: c.option('from'));
  var anyOk = false;
  for (final r in results) {
    (r.ok ? o : e).writeln('${r.platform.padRight(8)} ${r.message}');
    anyOk |= r.ok;
  }
  if (anyOk && spec.ios != null) _iosCaches(c, env, o);
  return anyOk ? exitOk : exitProblems;
}

int _unlink(
  HuskSpec spec,
  ArgResults c,
  Map<String, String> env,
  StringSink o,
) {
  if (_commandHelp(c, o)) return exitOk;
  final removed = unlink(spec);
  if (removed.isEmpty) {
    o.writeln('Nothing to remove.');
  } else {
    for (final r in removed) {
      o.writeln('removed  $r/');
    }
    if (spec.ios != null) _iosCaches(c, env, o);
  }
  return exitOk;
}

void _iosCaches(ArgResults c, Map<String, String> env, StringSink o) {
  o.writeln();
  if (c.flag('clear-swiftpm-cache')) {
    final cleared = clearSwiftPmManifestCache(env);
    o.writeln(
      cleared == null
          ? 'No Swift Package Manager manifest cache to clear.'
          : 'Cleared the Swift Package Manager manifest cache '
                '(${_tilde(cleared, env)}).',
    );
  } else {
    o
      ..writeln('Swift Package Manager caches Package.swift by its text and')
      ..writeln('environment, so the next build may not notice this change.')
      ..writeln('Re-run with --clear-swiftpm-cache, or build with any changed')
      ..writeln('environment variable (doc/traps.md).');
  }
  o.writeln('CocoaPods: run `pod install` in the app\'s ios/ folder.');
}

int _report(
  HuskSpec spec,
  ArgResults c,
  Map<String, String> env,
  StringSink o, {
  required bool strict,
}) {
  if (_commandHelp(c, o)) return exitOk;
  final sections = diagnose(
    spec,
    env: env,
    from: c.option('from'),
    requireSdk: strict ? c.multiOption('require-sdk').toSet() : const {},
  );
  final errors = [
    for (final s in sections)
      for (final f in s.findings)
        if (f.level == Level.error) f,
  ].length;
  // `check` fails on errors. `doctor` prints the same number and still exits 0.
  final checkExit = errors > 0 ? exitProblems : exitOk;
  if (c.flag('json')) {
    o.writeln(
      jsonEncode(_reportJson(sections, strict: strict, exitCode: checkExit)),
    );
    return strict ? checkExit : exitOk;
  }
  var warnings = 0;
  o.writeln(
    'husk_sdk ${strict ? 'check' : 'doctor'}: ${spec.sdkName} '
    '(plugin ${spec.plugin})',
  );
  for (final s in sections) {
    final shown = _visible(s, strict);
    warnings += s.findings.where((f) => f.level == Level.warning).length;
    if (shown.isEmpty) continue;
    o
      ..writeln()
      ..writeln(s.title);
    for (final f in shown) {
      o.writeln('  ${_tag(f.level)} ${f.message}');
      for (final d in f.detail) {
        o.writeln('         $d');
      }
    }
  }
  o
    ..writeln()
    ..writeln(
      '$errors error${errors == 1 ? '' : 's'}, '
      '$warnings warning${warnings == 1 ? '' : 's'}.',
    );
  if (!strict) return exitOk;
  return checkExit;
}

/// JSON shape of a `doctor` or `check` report.
///
/// [exitCode] is the code `check` would use. Sections and findings match
/// the text report: `check` keeps warnings and errors, `doctor` keeps all.
Map<String, Object> _reportJson(
  List<Section> sections, {
  required bool strict,
  required int exitCode,
}) {
  return {
    'sections': [
      for (final s in sections)
        if (_visible(s, strict).isNotEmpty)
          {
            'title': s.title,
            'findings': [
              for (final f in _visible(s, strict))
                {
                  'level': f.level.name,
                  'message': f.message,
                  'detail': f.detail,
                },
            ],
          },
    ],
    'exitCode': exitCode,
  };
}

List<Finding> _visible(Section section, bool strict) => strict
    ? section.findings
          .where((f) => f.level.index >= Level.warning.index)
          .toList()
    : section.findings;

String _tilde(String path, Map<String, String> env) {
  final home = env['HOME'];
  return home != null && home.isNotEmpty && p.isWithin(home, path)
      ? '~/${p.split(p.relative(path, from: home)).join('/')}'
      : path;
}

String _tag(Level level) => switch (level) {
  Level.ok => 'ok   ',
  Level.info => 'info ',
  Level.warning => 'warn ',
  Level.error => 'error',
};
