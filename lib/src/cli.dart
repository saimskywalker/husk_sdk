      ('android-package', 'pkg', 'Kotlin package for generated code.'),
      ('[no-]ios', null, 'Configure iOS (default: if ios/ exists).'),
      (
        '[no-]android',
        null,
        'Configure Android (default: if android/ exists).',
      ),
      ('native', null, 'Wire a plain iOS/Android app, not a Flutter plugin.'),
      ('force', null, 'Overwrite an existing husk.yaml.'),
    ],
  ),
  'generate': (
    'Write the SwiftPM, CocoaPods, Gradle and Dart glue.',
    [
      ('dry-run', null, 'Show what would change; write nothing.'),
